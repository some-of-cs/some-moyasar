//! Apple Pay Web Merchant session initiation types and request handler (US-7.1.0 Unit 2).

use http::header::CONTENT_TYPE;
use serde::{Deserialize, Serialize};

use crate::kernel::auth::PublishableAuthKey;
use crate::kernel::client::MoyasarClient;
use crate::kernel::error::{ApiErrorType, MoyasarError};
use crate::kernel::transport::execute_with_retry;

const APPLE_PAY_INITIATE_PATH: &str = "/v1/applepay/initiate";

/// Signed Apple Pay Web Merchant session returned by `POST /v1/applepay/initiate`.
///
/// Apple Pay Web Merchant session responses use camelCase JSON field names
/// (`epochTimestamp`, `expiresAt`, `merchantSessionIdentifier`, etc.).
///
/// # Examples
///
/// ```
/// use some_moyasar::resources::sources::apple_pay::ApplePayMerchantSession;
///
/// let json = r#"{
///     "epochTimestamp": 1700000000000,
///     "expiresAt": 1700003600000,
///     "merchantSessionIdentifier": "SSH1234567890",
///     "nonce": "abcdef12",
///     "merchantIdentifier": "merchant.com.example",
///     "domainName": "checkout.example.com",
///     "displayName": "Example Store",
///     "signature": "MIAGCSqGSIb3DQEHAqCAMIACAQExDzANBglghkgBZQMEAgEFADCABgkqhkiG9w0BBwEAAKCAMIAwgg..."
/// }"#;
///
/// let session: ApplePayMerchantSession = serde_json::from_str(json).unwrap();
/// assert_eq!(session.merchant_session_identifier, "SSH1234567890");
/// assert_eq!(session.domain_name, "checkout.example.com");
/// assert_eq!(session.retries, None);
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ApplePayMerchantSession {
    /// Unix epoch timestamp in milliseconds when the session was created.
    pub epoch_timestamp: u64,
    /// Unix epoch timestamp in milliseconds when the session expires.
    pub expires_at: u64,
    /// Unique identifier for the Apple Pay merchant session.
    pub merchant_session_identifier: String,
    /// Cryptographic nonce generated by Apple Pay servers.
    pub nonce: String,
    /// Apple Merchant ID associated with the session.
    pub merchant_identifier: String,
    /// Verified merchant domain name for the web session.
    pub domain_name: String,
    /// Merchant display name shown in the Apple Pay payment sheet.
    pub display_name: String,
    /// Cryptographic PKCS#7 signature over the session payload.
    pub signature: String,
    /// Optional identifier used by Apple Pay operational analytics.
    pub operational_analytics_identifier: Option<String>,
    /// Optional retry counter returned by Apple Pay servers.
    pub retries: Option<u32>,
}

/// Validates that an Apple Pay validation URL uses `https://` with a non-empty host
/// and contains no whitespace.
pub(crate) fn validate_apple_pay_url(url: &str) -> Result<(), MoyasarError> {
    let Some(rest) = url.strip_prefix("https://") else {
        return Err(MoyasarError::InvalidBaseUrl);
    };
    let host = rest.split(['/', '?', '#']).next().unwrap_or("");
    let valid_host = !host.is_empty()
        && (host.contains('.') || host == "localhost" || host.starts_with("localhost:"));
    if !valid_host || url.chars().any(char::is_whitespace) {
        return Err(MoyasarError::InvalidBaseUrl);
    }
    Ok(())
}

/// Request parameters for initiating an Apple Pay Web Merchant session
/// (`POST /v1/applepay/initiate`).
///
/// Enforces that `validation_url` uses the `https://` scheme before any
/// network transport occurs.
///
/// # Examples
///
/// ```
/// use some_moyasar::kernel::error::MoyasarError;
/// use some_moyasar::resources::sources::apple_pay::InitiateApplePayParams;
///
/// let params = InitiateApplePayParams::new(
///     "https://apple-pay-gateway.apple.com/paymentservices/paymentSession",
///     "Example Store",
///     "checkout.example.com",
///     "pk_test_abc123",
/// )
/// .unwrap();
/// assert_eq!(params.domain_name, "checkout.example.com");
///
/// let err = InitiateApplePayParams::new(
///     "http://apple-pay-gateway.apple.com/paymentservices/paymentSession",
///     "Example Store",
///     "checkout.example.com",
///     "pk_test_abc123",
/// )
/// .unwrap_err();
/// assert!(matches!(err, MoyasarError::InvalidBaseUrl));
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct InitiateApplePayParams {
    /// Apple Pay validation URL provided by `PKPaymentAuthorizationController` (must be `https://`).
    pub validation_url: String,
    /// Merchant display name shown on the Apple Pay payment sheet.
    pub display_name: String,
    /// Verified merchant domain name initiating the session.
    pub domain_name: String,
    /// Publishable Moyasar API key (`pk_live_...` or `pk_test_...`).
    pub publishable_api_key: String,
}

impl InitiateApplePayParams {
    /// Creates and validates a new [`InitiateApplePayParams`] payload.
    ///
    /// # Errors
    ///
    /// Returns [`MoyasarError::InvalidBaseUrl`] if `validation_url` is not a valid `https://` URL.
    pub fn new(
        validation_url: impl Into<String>,
        display_name: impl Into<String>,
        domain_name: impl Into<String>,
        publishable_api_key: impl Into<String>,
    ) -> Result<Self, MoyasarError> {
        let validation_url = validation_url.into();
        validate_apple_pay_url(&validation_url)?;
        Ok(Self {
            validation_url,
            display_name: display_name.into(),
            domain_name: domain_name.into(),
            publishable_api_key: publishable_api_key.into(),
        })
    }
}

/// Sends `POST /v1/applepay/initiate` using a publishable key client and bounded retry transport.
pub(crate) async fn initiate_session_request<K: PublishableAuthKey>(
    client: &MoyasarClient<K>,
    params: &InitiateApplePayParams,
) -> Result<ApplePayMerchantSession, MoyasarError> {
    post_initiate_session(client, &client.config().base_url, params).await
}

async fn post_initiate_session<K: PublishableAuthKey>(
    client: &MoyasarClient<K>,
    base_url: &str,
    params: &InitiateApplePayParams,
) -> Result<ApplePayMerchantSession, MoyasarError> {
    validate_apple_pay_url(&params.validation_url)?;
    let url = format!(
        "{}{}",
        base_url.trim_end_matches('/'),
        APPLE_PAY_INITIATE_PATH
    );
    let max_retries = client.config().max_network_retries;
    let (status, body) = execute_with_retry(max_retries, || async {
        dispatch_post(client.http(), &url, params).await
    })
    .await?;
    parse_session_response(status, &body)
}

async fn dispatch_post(
    http: &reqwest::Client,
    url: &str,
    params: &InitiateApplePayParams,
) -> Result<(u16, String), MoyasarError> {
    let response = http
        .post(url)
        .header(CONTENT_TYPE, "application/json")
        .json(params)
        .send()
        .await
        .map_err(MoyasarError::from)?;
    let status = response.status().as_u16();
    let body = response.text().await.map_err(MoyasarError::from)?;
    if status >= 500 {
        return Err(MoyasarError::from_api_response(status, &body));
    }
    Ok((status, body))
}


fn parse_session_response(
    status: u16,
    body: &str,
) -> Result<ApplePayMerchantSession, MoyasarError> {
    if !(200..300).contains(&status) {
        return Err(MoyasarError::from_api_response(status, body));
    }
    serde_json::from_str::<ApplePayMerchantSession>(body).map_err(|err| MoyasarError::Api {
        error_type: ApiErrorType::Unknown,
        message: format!("failed to decode Apple Pay session response: {err}"),
        errors: Vec::new(),
        response_code: None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::kernel::auth::PublishableKey;
    use crate::kernel::transport::{API_VERSION, MOYASAR_VERSION_HEADER};
    use std::sync::atomic::{AtomicU32, Ordering};
    use wiremock::matchers::{body_json, header, header_exists, method, path};
    use wiremock::{Mock, MockServer, Request, Respond, ResponseTemplate};

    fn sample_session_json() -> serde_json::Value {
        serde_json::json!({
            "epochTimestamp": 1700000000000_u64,
            "expiresAt": 1700003600000_u64,
            "merchantSessionIdentifier": "SSH1234567890",
            "nonce": "nonce_abc123",
            "merchantIdentifier": "merchant.com.moyasar.store",
            "domainName": "store.example.com",
            "displayName": "Example Store",
            "signature": "sig_pkcs7_payload",
            "operationalAnalyticsIdentifier": "analytics_01",
            "retries": 0
        })
    }

    #[test]
    fn deserializes_camel_case_merchant_session() {
        let full: ApplePayMerchantSession =
            serde_json::from_value(sample_session_json()).expect("deserialize full session");
        assert_eq!(full.epoch_timestamp, 1_700_000_000_000);
        assert_eq!(full.expires_at, 1_700_003_600_000);
        assert_eq!(full.merchant_session_identifier, "SSH1234567890");
        assert_eq!(full.nonce, "nonce_abc123");
        assert_eq!(full.merchant_identifier, "merchant.com.moyasar.store");
        assert_eq!(full.domain_name, "store.example.com");
        assert_eq!(full.display_name, "Example Store");
        assert_eq!(full.signature, "sig_pkcs7_payload");
        assert_eq!(
            full.operational_analytics_identifier.as_deref(),
            Some("analytics_01")
        );
        assert_eq!(full.retries, Some(0));

        let minimal_json = serde_json::json!({
            "epochTimestamp": 1700000000000_u64,
            "expiresAt": 1700003600000_u64,
            "merchantSessionIdentifier": "SSH_MIN",
            "nonce": "n1",
            "merchantIdentifier": "merchant.com.min",
            "domainName": "min.example.com",
            "displayName": "Min Store",
            "signature": "sig_min"
        });
        let minimal: ApplePayMerchantSession =
            serde_json::from_value(minimal_json).expect("deserialize minimal session");
        assert_eq!(minimal.operational_analytics_identifier, None);
        assert_eq!(minimal.retries, None);
    }

    #[test]
    fn validates_https_validation_url_pre_transport() {
        let valid = InitiateApplePayParams::new(
            "https://apple-pay-gateway.apple.com/paymentservices/paymentSession",
            "Example Store",
            "store.example.com",
            "pk_test_123",
        )
        .expect("https URL accepted");
        assert_eq!(
            valid.validation_url,
            "https://apple-pay-gateway.apple.com/paymentservices/paymentSession"
        );

        for bad_url in [
            "http://apple-pay-gateway.apple.com/paymentservices/paymentSession",
            "ftp://apple-pay-gateway.apple.com/session",
            "apple-pay-gateway.apple.com/session",
            "https://",
            "https:///paymentservices/paymentSession",
            "https://apple-pay-gateway.apple.com/payment services",
            "",
        ] {
            let err = InitiateApplePayParams::new(
                bad_url,
                "Example Store",
                "store.example.com",
                "pk_test_123",
            )
            .expect_err("non-https or malformed URL must be rejected");
            assert!(matches!(err, MoyasarError::InvalidBaseUrl));
        }
    }

    #[tokio::test]
    async fn ac_us_7_1_0_03_initiates_session_with_publishable_key() {
        let server = MockServer::start().await;
        let expected_body = serde_json::json!({
            "validation_url": "https://apple-pay-gateway.apple.com/paymentservices/paymentSession",
            "display_name": "Example Store",
            "domain_name": "store.example.com",
            "publishable_api_key": "pk_test_unit2_pub"
        });

        Mock::given(method("POST"))
            .and(path("/v1/applepay/initiate"))
            .and(header_exists("authorization"))
            .and(header(MOYASAR_VERSION_HEADER, API_VERSION))
            .and(body_json(&expected_body))
            .respond_with(ResponseTemplate::new(200).set_body_json(sample_session_json()))
            .expect(1)
            .mount(&server)
            .await;

        let pk = PublishableKey::new("pk_test_unit2_pub").expect("valid publishable key");
        let client = MoyasarClient::new(pk).expect("client builds");
        let params = InitiateApplePayParams::new(
            "https://apple-pay-gateway.apple.com/paymentservices/paymentSession",
            "Example Store",
            "store.example.com",
            "pk_test_unit2_pub",
        )
        .expect("valid params");

        let session = post_initiate_session(&client, &server.uri(), &params)
            .await
            .expect("session initiated");
        assert_eq!(session.merchant_session_identifier, "SSH1234567890");
        assert_eq!(session.signature, "sig_pkcs7_payload");
    }

    #[tokio::test]
    async fn rejects_http_validation_url_before_network_call() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/v1/applepay/initiate"))
            .respond_with(ResponseTemplate::new(200).set_body_json(sample_session_json()))
            .expect(0)
            .mount(&server)
            .await;

        let pk = PublishableKey::new("pk_test_unit2_pub").expect("valid publishable key");
        let client = MoyasarClient::new(pk).expect("client builds");
        let tampered = InitiateApplePayParams {
            validation_url: "http://insecure.example.com/session".to_owned(),
            display_name: "Example Store".to_owned(),
            domain_name: "store.example.com".to_owned(),
            publishable_api_key: "pk_test_unit2_pub".to_owned(),
        };

        let err = post_initiate_session(&client, &server.uri(), &tampered)
            .await
            .expect_err("http URL must fail pre-transport");
        assert!(matches!(err, MoyasarError::InvalidBaseUrl));
    }

    struct FlakyResponder {
        attempts: AtomicU32,
    }

    impl Respond for FlakyResponder {
        fn respond(&self, _request: &Request) -> ResponseTemplate {
            let attempt = self.attempts.fetch_add(1, Ordering::SeqCst);
            if attempt == 0 {
                ResponseTemplate::new(503).set_body_string("Service Unavailable")
            } else {
                ResponseTemplate::new(200).set_body_json(sample_session_json())
            }
        }
    }

    #[tokio::test]
    async fn retries_transient_5xx_and_fails_fast_on_422() {
        let server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/v1/applepay/initiate"))
            .respond_with(FlakyResponder {
                attempts: AtomicU32::new(0),
            })
            .expect(2)
            .mount(&server)
            .await;

        let pk = PublishableKey::new("pk_test_retry").expect("valid key");
        let client = MoyasarClient::new(pk).expect("client builds");
        let params = InitiateApplePayParams::new(
            "https://apple-pay-gateway.apple.com/paymentservices/paymentSession",
            "Example Store",
            "store.example.com",
            "pk_test_retry",
        )
        .expect("valid params");

        let session = post_initiate_session(&client, &server.uri(), &params)
            .await
            .expect("recovers after 503");
        assert_eq!(session.merchant_session_identifier, "SSH1234567890");

        let err_server = MockServer::start().await;
        Mock::given(method("POST"))
            .and(path("/v1/applepay/initiate"))
            .respond_with(ResponseTemplate::new(422).set_body_json(serde_json::json!({
                "type": "invalid_request_error",
                "message": "Invalid domain_name"
            })))
            .expect(1)
            .mount(&err_server)
            .await;

        let err = post_initiate_session(&client, &err_server.uri(), &params)
            .await
            .expect_err("422 must fail immediately");
        assert!(matches!(
            err,
            MoyasarError::Api {
                error_type: ApiErrorType::InvalidRequestError,
                ..
            }
        ));
    }
}
